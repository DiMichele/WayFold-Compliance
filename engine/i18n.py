def normalize_lang(value: str | None) -> str:
    if not value:
        return DEFAULT_LANG
    code = value.strip().lower()[:2]
    return code if code in SUPPORTED_LANGS else DEFAULT_LANG


def lang_from_qs(qs: dict[str, Any] | None) -> str:
    if not qs:
        return DEFAULT_LANG
    raw = qs.get("lang", [DEFAULT_LANG])
    if isinstance(raw, list):
        return normalize_lang(raw[0] if raw else None)
    return normalize_lang(str(raw))


def t(lang: str, key: str, **kwargs: Any) -> str:
    lang = normalize_lang(lang)
    text = MESSAGES.get(lang, {}).get(key) or MESSAGES[DEFAULT_LANG].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def with_lang(nav_qs: str, lang: str) -> str:
    data = dict(parse_qsl(nav_qs, keep_blank_values=False))
    data["lang"] = normalize_lang(lang)
    return urlencode(data)


def nav_labels(lang: str, keys: tuple[tuple[str, str], ...] | None = None) -> list[tuple[str, str]]:
    items = keys or DEFAULT_NAV_KEYS
    return [(t(lang, key), path) for key, path in items]
